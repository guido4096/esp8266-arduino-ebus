#!/usr/bin/env python3
"""Update the build stamp only when project inputs change.

An unchanged build must not recompile API sources and relink just because
wall clock time advanced. The digest excludes this generated header itself.
"""

import hashlib
from pathlib import Path
import time

try:
    Import("env")
    PROJECT_ROOT = Path(env["PROJECT_SRC_DIR"]).parent
    BUILD_FLAGS = repr(env.get("BUILD_FLAGS", [])).encode()
    LIBRARY_ROOTS = [
        (PROJECT_ROOT / dependency[len("symlink://"):]).resolve()
        for dependency in env.GetProjectOption("lib_deps", [])
        if dependency.startswith("symlink://")
    ]
except NameError:
    PROJECT_ROOT = Path(__file__).resolve().parent.parent
    BUILD_FLAGS = b""
    LIBRARY_ROOTS = []


def generate(project_root, build_flags=b"", library_roots=()):
    output = project_root / "include/app/build_info_gen.hpp"
    digest = hashlib.sha256(build_flags)
    inputs = []
    for directory in ("src", "include", "static", "profiles", "scripts"):
        inputs.extend(path for path in (project_root / directory).rglob("*")
                      if path.is_file() and path != output
                      and "__pycache__" not in path.parts)
    for pattern in ("*.py", "*.ini", "*.csv", "sdkconfig.defaults", "CMakeLists.txt"):
        inputs.extend(project_root.glob(pattern))
    for library_root in library_roots:
        for directory in ("src", "include"):
            inputs.extend(path for path in (library_root / directory).rglob("*")
                          if path.is_file() and "__pycache__" not in path.parts)
        for name in ("library.json", "library.properties", "CMakeLists.txt"):
            path = library_root / name
            if path.is_file():
                inputs.append(path)
    for path in sorted(set(inputs)):
        digest.update(str(path).encode())
        digest.update(b"\0")
        digest.update(path.read_bytes())
        digest.update(b"\0")
    marker = "// Build input digest: " + digest.hexdigest() + "\n"
    if output.exists() and marker in output.read_text(encoding="utf-8"):
        return

    now = int(time.time())
    utc = time.strftime("%Y-%m-%d %H:%M:%S", time.gmtime(now))
    content = (
        "#pragma once\n"
        "// Auto-generated by scripts/generate_build_info.py; do not edit.\n"
        + marker
        + f"inline constexpr long long build_epoch = {now}LL;\n"
        + f'inline constexpr char build_time_str[] = "{utc}";\n'
    )
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(content, encoding="utf-8")


# PlatformIO executes extra_scripts without setting __name__ to __main__.
generate(PROJECT_ROOT, BUILD_FLAGS, LIBRARY_ROOTS)
